package rs.ac.ftn.isa.uploadeventconsumer.benchmark;

import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Map;
import java.util.concurrent.CopyOnWriteArrayList;

@Service
public class BenchmarkService {

    private static final int MIN_MESSAGES_FOR_REPORT = 50;

    private final CopyOnWriteArrayList<MetricEntry> jsonMetrics = new CopyOnWriteArrayList<>();
    private final CopyOnWriteArrayList<MetricEntry> protobufMetrics = new CopyOnWriteArrayList<>();

    private volatile boolean reportPrinted = false;

    public void recordJson(long serializationTimeNanos, long deserializationTimeNanos, int messageSizeBytes) {
        jsonMetrics.add(new MetricEntry(serializationTimeNanos, deserializationTimeNanos, messageSizeBytes));
        checkAndPrintReport();
    }

    public void recordProtobuf(long serializationTimeNanos, long deserializationTimeNanos, int messageSizeBytes) {
        protobufMetrics.add(new MetricEntry(serializationTimeNanos, deserializationTimeNanos, messageSizeBytes));
        checkAndPrintReport();
    }

    private void checkAndPrintReport() {
        if (!reportPrinted
                && jsonMetrics.size() >= MIN_MESSAGES_FOR_REPORT
                && protobufMetrics.size() >= MIN_MESSAGES_FOR_REPORT) {
            reportPrinted = true;
            printReport();
        }
    }

    public void resetMetrics() {
        jsonMetrics.clear();
        protobufMetrics.clear();
        reportPrinted = false;
    }

    public Map<String, Object> getReport() {
        return Map.of(
                "jsonCount", jsonMetrics.size(),
                "protobufCount", protobufMetrics.size(),
                "json", computeStats(jsonMetrics),
                "protobuf", computeStats(protobufMetrics),
                "reportAutoGenerated", reportPrinted
        );
    }

    private void printReport() {
        double jsonAvgSer = avg(jsonMetrics, MetricEntry::serializationTimeNanos);
        double jsonAvgDeser = avg(jsonMetrics, MetricEntry::deserializationTimeNanos);
        double jsonAvgSize = avg(jsonMetrics, e -> (long) e.messageSizeBytes());

        double protoAvgSer = avg(protobufMetrics, MetricEntry::serializationTimeNanos);
        double protoAvgDeser = avg(protobufMetrics, MetricEntry::deserializationTimeNanos);
        double protoAvgSize = avg(protobufMetrics, e -> (long) e.messageSizeBytes());

        System.out.println("\n" + "=".repeat(70));
        System.out.println("  BENCHMARK REPORT: JSON vs Protobuf (" + jsonMetrics.size() + " messages each)");
        System.out.println("=".repeat(70));

        System.out.printf("  %-30s %15s %15s%n", "Metric", "JSON", "Protobuf");
        System.out.println("-".repeat(70));

        System.out.printf("  %-30s %12.1f us %12.1f us%n",
                "Avg Serialization Time", jsonAvgSer / 1000, protoAvgSer / 1000);
        System.out.printf("  %-30s %12.1f us %12.1f us%n",
                "Avg Deserialization Time", jsonAvgDeser / 1000, protoAvgDeser / 1000);
        System.out.printf("  %-30s %12.1f B  %12.1f B%n",
                "Avg Message Size", jsonAvgSize, protoAvgSize);

        System.out.println("-".repeat(70));

        printWinner("Serialization Speed", jsonAvgSer, protoAvgSer);
        printWinner("Deserialization Speed", jsonAvgDeser, protoAvgDeser);
        printWinner("Message Size", jsonAvgSize, protoAvgSize);

        System.out.println("=".repeat(70) + "\n");
    }

    private void printWinner(String category, double jsonVal, double protoVal) {
        if (protoVal < jsonVal) {
            System.out.printf("  %-30s WINNER: Protobuf (%.2fx faster/smaller)%n",
                    category, jsonVal / protoVal);
        } else if (jsonVal < protoVal) {
            System.out.printf("  %-30s WINNER: JSON (%.2fx faster/smaller)%n",
                    category, protoVal / jsonVal);
        } else {
            System.out.printf("  %-30s TIE%n", category);
        }
    }

    private Map<String, Object> computeStats(List<MetricEntry> metrics) {
        if (metrics.isEmpty()) {
            return Map.of(
                    "count", 0,
                    "avgSerializationTimeUs", 0.0,
                    "avgDeserializationTimeUs", 0.0,
                    "avgMessageSizeBytes", 0.0
            );
        }
        return Map.of(
                "count", metrics.size(),
                "avgSerializationTimeUs", avg(metrics, MetricEntry::serializationTimeNanos) / 1000.0,
                "avgDeserializationTimeUs", avg(metrics, MetricEntry::deserializationTimeNanos) / 1000.0,
                "avgMessageSizeBytes", avg(metrics, e -> (long) e.messageSizeBytes())
        );
    }

    private double avg(List<MetricEntry> list, java.util.function.ToLongFunction<MetricEntry> extractor) {
        return list.stream().mapToLong(extractor).average().orElse(0.0);
    }

    record MetricEntry(long serializationTimeNanos, long deserializationTimeNanos, int messageSizeBytes) {}
}
